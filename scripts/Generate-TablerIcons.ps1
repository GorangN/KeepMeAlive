<#
.SYNOPSIS
Converts the pinned Tabler outline sources to native WPF geometry and Windows icon assets.
.DESCRIPTION
Run with Windows PowerShell in STA mode. This generator uses only vendored sources,
verifies their hashes, and makes no network requests.
#>
[CmdletBinding()]
param()
$ErrorActionPreference = 'Stop'
Set-StrictMode -Version Latest
Add-Type -AssemblyName PresentationFramework, PresentationCore, WindowsBase
$repository = Split-Path $PSScriptRoot -Parent
$iconRoot = Join-Path $repository 'KeepMeAlive/Resources/Icons'
$sourceRoot = Join-Path $iconRoot 'Tabler'
$manifest = Get-Content -LiteralPath (Join-Path $sourceRoot 'manifest.json') -Raw | ConvertFrom-Json
if ((Get-FileHash -LiteralPath (Join-Path $sourceRoot $manifest.licenseFile) -Algorithm SHA256).Hash -ne $manifest.licenseSha256) { throw 'The pinned Tabler license checksum does not match.' }
$culture = [Globalization.CultureInfo]::InvariantCulture
function Escape-Xml([string]$Value) { return [Security.SecurityElement]::Escape($Value) }
function Read-Number($Node, [string]$Name, [double]$Fallback = 0) {
    $value = $Node.GetAttribute($Name)
    if (-not $value) { return $Fallback }
    return [double]::Parse($value, $culture)
}
function Convert-Shape($Node) {
    if ($Node.GetAttribute('stroke') -eq 'none' -and $Node.GetAttribute('fill') -eq 'none') { return '' }
    $allowed = @{
        path = @('d'); line = @('x1', 'y1', 'x2', 'y2'); circle = @('cx', 'cy', 'r')
        ellipse = @('cx', 'cy', 'rx', 'ry'); rect = @('x', 'y', 'width', 'height', 'rx', 'ry')
        polyline = @('points'); polygon = @('points')
    }
    if (-not $allowed.ContainsKey($Node.LocalName)) { throw "Unsupported SVG element: $($Node.LocalName)." }
    foreach ($attribute in $Node.Attributes) {
        if ($attribute.Name -notin $allowed[$Node.LocalName]) {
            throw "Unsupported SVG attribute $($attribute.Name) on $($Node.LocalName)."
        }
    }
    switch ($Node.LocalName) {
        'path' { return '<PathGeometry Figures="' + (Escape-Xml $Node.GetAttribute('d')) + '" />' }
        'line' { return '<LineGeometry StartPoint="' + $Node.GetAttribute('x1') + ',' + $Node.GetAttribute('y1') + '" EndPoint="' + $Node.GetAttribute('x2') + ',' + $Node.GetAttribute('y2') + '" />' }
        'circle' { return '<EllipseGeometry Center="' + $Node.GetAttribute('cx') + ',' + $Node.GetAttribute('cy') + '" RadiusX="' + $Node.GetAttribute('r') + '" RadiusY="' + $Node.GetAttribute('r') + '" />' }
        'ellipse' { return '<EllipseGeometry Center="' + $Node.GetAttribute('cx') + ',' + $Node.GetAttribute('cy') + '" RadiusX="' + $Node.GetAttribute('rx') + '" RadiusY="' + $Node.GetAttribute('ry') + '" />' }
        'rect' {
            $x = (Read-Number $Node 'x').ToString($culture)
            $y = (Read-Number $Node 'y').ToString($culture)
            $rx = Read-Number $Node 'rx' (Read-Number $Node 'ry')
            $ry = Read-Number $Node 'ry' $rx
            return '<RectangleGeometry Rect="' + $x + ',' + $y + ',' + $Node.GetAttribute('width') + ',' + $Node.GetAttribute('height') + '" RadiusX="' + $rx.ToString($culture) + '" RadiusY="' + $ry.ToString($culture) + '" />'
        }
        { $_ -in @('polyline', 'polygon') } {
            $points = $Node.GetAttribute('points').Trim()
            if (-not $points) { throw 'SVG points must not be empty.' }
            $closed = ''
            if ($Node.LocalName -eq 'polygon') { $closed = ' Z' }
            return '<PathGeometry Figures="M' + (Escape-Xml $points) + $closed + '" />'
        }
        default { throw "Unsupported SVG element: $($Node.LocalName)." }
    }
}
$lines = [Collections.Generic.List[string]]::new()
$lines.Add('<ResourceDictionary xmlns="http://schemas.microsoft.com/winfx/2006/xaml/presentation" xmlns:x="http://schemas.microsoft.com/winfx/2006/xaml">')
$lines.Add('    <!-- Generated by scripts/Generate-TablerIcons.ps1 from pinned MIT-licensed Tabler sources. -->')
foreach ($icon in $manifest.icons) {
    if ($icon.key -notmatch '^Tabler\.[A-Za-z]+$' -or $icon.file -notmatch '^[a-z-]+\.svg$') { throw 'Invalid icon manifest entry.' }
    $path = Join-Path $sourceRoot $icon.file
    if ((Get-FileHash -LiteralPath $path -Algorithm SHA256).Hash -ne $icon.sha256) { throw "Source checksum mismatch: $($icon.file)." }
    $settings = [Xml.XmlReaderSettings]::new()
    $settings.DtdProcessing = [Xml.DtdProcessing]::Prohibit
    $settings.XmlResolver = $null
    $reader = [Xml.XmlReader]::Create($path, $settings)
    try { $document = [Xml.XmlDocument]::new(); $document.Load($reader) }
    finally { $reader.Dispose() }
    $svg = $document.DocumentElement
    if ($svg.LocalName -ne 'svg' -or $svg.GetAttribute('viewBox') -ne $manifest.viewBox -or $svg.GetAttribute('stroke-width') -ne '2' -or $svg.GetAttribute('fill') -ne 'none' -or $svg.GetAttribute('stroke') -ne 'currentColor' -or $svg.GetAttribute('stroke-linecap') -ne 'round' -or $svg.GetAttribute('stroke-linejoin') -ne 'round') { throw "Unsupported Tabler root attributes: $($icon.file)." }
    $lines.Add('    <GeometryGroup x:Key="' + $icon.key + '">')
    foreach ($child in $svg.ChildNodes) {
        if ($child.NodeType -eq [Xml.XmlNodeType]::Element) {
            $shape = Convert-Shape $child
            if ($shape) { $lines.Add('        ' + $shape) }
        }
    }
    $lines.Add('    </GeometryGroup>')
}
$sourceResources = [Windows.Markup.XamlReader]::Parse(($lines -join "`n") + '</ResourceDictionary>')
$arrowPen = [Windows.Media.Pen]::new([Windows.Media.Brushes]::Black, 2)
$arrowPen.StartLineCap = [Windows.Media.PenLineCap]::Round
$arrowPen.EndLineCap = [Windows.Media.PenLineCap]::Round
$arrowPen.LineJoin = [Windows.Media.PenLineJoin]::Round
$widenedArrow = $sourceResources['Tabler.ChevronDown'].GetWidenedPathGeometry($arrowPen)
$arrowDocument = [Xml.XmlDocument]::new()
$arrowDocument.LoadXml([Windows.Markup.XamlWriter]::Save($widenedArrow))
$arrowKey = $arrowDocument.CreateAttribute('x', 'Key', 'http://schemas.microsoft.com/winfx/2006/xaml')
$arrowKey.Value = 'ComboBoxDownArrowGeometry'
[void]$arrowDocument.DocumentElement.Attributes.Append($arrowKey)
$lines.Add('    ' + $arrowDocument.DocumentElement.OuterXml)
$lines.Add(@'
    <Style x:Key="TablerIconStyle" TargetType="ContentControl">
        <Setter Property="Width" Value="18" />
        <Setter Property="Height" Value="18" />
        <Setter Property="Focusable" Value="False" />
        <Setter Property="IsHitTestVisible" Value="False" />
        <Setter Property="VerticalAlignment" Value="Center" />
        <Setter Property="HorizontalAlignment" Value="Center" />
        <Setter Property="Template">
            <Setter.Value>
                <ControlTemplate TargetType="ContentControl">
                    <Viewbox Stretch="Uniform">
                        <Canvas Width="24" Height="24">
                            <Path Data="{TemplateBinding Content}" Stroke="{TemplateBinding Foreground}" StrokeThickness="2"
                                  StrokeStartLineCap="Round" StrokeEndLineCap="Round" StrokeLineJoin="Round" />
                        </Canvas>
                    </Viewbox>
                </ControlTemplate>
            </Setter.Value>
        </Setter>
    </Style>
</ResourceDictionary>
'@)
$dictionaryPath = Join-Path $iconRoot 'Tabler.xaml'
[IO.File]::WriteAllText($dictionaryPath, (($lines -join "`n") + "`n").Replace("`r`n", "`n"), [Text.UTF8Encoding]::new($false))
$resources = [Windows.Markup.XamlReader]::Parse([IO.File]::ReadAllText($dictionaryPath))
$activity = $resources['Tabler.Activity']
$activity.Freeze()
function Render-Activity([int]$Width, [int]$Height, [double]$IconSize, [string]$Color, [bool]$Opaque) {
    $visual = [Windows.Media.DrawingVisual]::new()
    $drawing = $visual.RenderOpen()
    try {
        if ($Opaque) { $drawing.DrawRectangle([Windows.Media.Brushes]::White, $null, [Windows.Rect]::new(0, 0, $Width, $Height)) }
        $offsetX = ($Width - $IconSize) / 2
        $offsetY = ($Height - $IconSize) / 2
        $drawing.PushTransform([Windows.Media.MatrixTransform]::new($IconSize / 24, 0, 0, $IconSize / 24, $offsetX, $offsetY))
        $brush = [Windows.Media.BrushConverter]::new().ConvertFromInvariantString($Color)
        $pen = [Windows.Media.Pen]::new($brush, 2)
        $pen.StartLineCap = [Windows.Media.PenLineCap]::Round
        $pen.EndLineCap = [Windows.Media.PenLineCap]::Round
        $pen.LineJoin = [Windows.Media.PenLineJoin]::Round
        $drawing.DrawGeometry($null, $pen, $activity)
        $drawing.Pop()
    }
    finally { $drawing.Close() }
    $bitmap = [Windows.Media.Imaging.RenderTargetBitmap]::new($Width, $Height, 96, 96, [Windows.Media.PixelFormats]::Pbgra32)
    $bitmap.Render($visual)
    return $bitmap
}
foreach ($state in @(@{ Name = 'inactive'; Color = '#636366' }, @{ Name = 'active'; Color = '#0066CC' })) {
    $sizes = @(16, 20, 24, 32, 48, 64, 128, 256)
    $images = [Collections.Generic.List[byte[]]]::new()
    foreach ($size in $sizes) {
        $bitmap = Render-Activity $size $size $size $state.Color $false
        $encoder = [Windows.Media.Imaging.PngBitmapEncoder]::new()
        $encoder.Frames.Add([Windows.Media.Imaging.BitmapFrame]::Create($bitmap))
        $stream = [IO.MemoryStream]::new()
        try { $encoder.Save($stream); $images.Add($stream.ToArray()) }
        finally { $stream.Dispose() }
    }
    $output = [IO.MemoryStream]::new()
    $writer = [IO.BinaryWriter]::new($output)
    try {
        $writer.Write([uint16]0); $writer.Write([uint16]1); $writer.Write([uint16]$sizes.Count)
        $offset = 6 + 16 * $sizes.Count
        for ($index = 0; $index -lt $sizes.Count; $index++) {
            $writer.Write([byte]($sizes[$index] % 256)); $writer.Write([byte]($sizes[$index] % 256))
            $writer.Write([byte]0); $writer.Write([byte]0); $writer.Write([uint16]1); $writer.Write([uint16]32)
            $writer.Write([uint32]$images[$index].Length); $writer.Write([uint32]$offset)
            $offset += $images[$index].Length
        }
        foreach ($bytes in $images) { $writer.Write($bytes) }
        [IO.File]::WriteAllBytes((Join-Path $iconRoot ('tray_' + $state.Name + '.ico')), $output.ToArray())
    }
    finally { $writer.Dispose(); $output.Dispose() }
}
foreach ($wizard in @(@{ Name = 'small'; Width = 55; Height = 55; Size = 40 }, @{ Name = 'large'; Width = 164; Height = 314; Size = 96 })) {
    $bitmap = Render-Activity $wizard.Width $wizard.Height $wizard.Size '#0066CC' $true
    $converted = [Windows.Media.Imaging.FormatConvertedBitmap]::new($bitmap, [Windows.Media.PixelFormats]::Bgr24, $null, 0)
    $encoder = [Windows.Media.Imaging.BmpBitmapEncoder]::new()
    $encoder.Frames.Add([Windows.Media.Imaging.BitmapFrame]::Create($converted))
    $stream = [IO.File]::Create((Join-Path $iconRoot ('wizard_' + $wizard.Name + '.bmp')))
    try { $encoder.Save($stream) }
    finally { $stream.Dispose() }
}
$outputs = foreach ($name in @('Tabler.xaml', 'tray_inactive.ico', 'tray_active.ico', 'wizard_small.bmp', 'wizard_large.bmp')) {
    [ordered]@{ file = $name; sha256 = (Get-FileHash -LiteralPath (Join-Path $iconRoot $name) -Algorithm SHA256).Hash.ToLowerInvariant() }
}
$checksums = [ordered]@{ sourceCommit = $manifest.commit; outputs = @($outputs) } | ConvertTo-Json -Depth 5
[IO.File]::WriteAllText((Join-Path $sourceRoot 'generated-checksums.json'), $checksums + "`n", [Text.UTF8Encoding]::new($false))
Write-Output "Generated $($manifest.icons.Count) pinned Tabler vectors, two multi-resolution ICOs, and installer artwork."
